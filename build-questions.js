/* ============================================================
   BUILD SCRIPT — run this locally (or in a CI/predeploy step)
   whenever you add/edit questions in /question-source/*.js

     node build-questions.js

   What it does:
   1. Executes every file in /question-source/*.js (your existing
      registerSubject / registerChapterText files, unchanged) in a
      sandboxed Node context using the SAME parser logic as
      js/parser.js.
   2. Writes the FULL question bank to
        server-data/questions-full.json
      This folder is never served to browsers (see vercel.json) —
      only the /api/questions.js function reads it. This is what
      actually stops people from viewing paid questions via
      "View Source" or fetching a JS/JSON file directly.
   3. Writes a small FREE sample (first N questions per chapter,
      see FREE_PER_CHAPTER below) to
        data/free-questions.js
      as a plain registerChapterObjects(...) call — this one IS
      public, loaded via <script> like before, so anonymous/free
      visitors can try the site with zero API calls.
   4. Writes server-data/meta.json — subject/chapter names + full
      counts (not the questions themselves) so the UI can show
      "5 free / 40 total" locks without needing to be logged in.
   ============================================================ */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const FREE_PER_CHAPTER = 5; // <-- change how many questions are free per chapter

const SOURCE_DIR = path.join(__dirname, "question-source");
const SERVER_DATA_DIR = path.join(__dirname, "server-data");
const DATA_DIR = path.join(__dirname, "data");

/* ---- same parser as js/parser.js, required verbatim (Node-safe, no DOM) ---- */
const parserSrc = fs.readFileSync(path.join(__dirname, "js", "parser.js"), "utf8");

const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(parserSrc, sandbox, { filename: "parser.js" });

// Run every question-source file in the same sandbox so they share window.SUBJECTS
const files = fs.readdirSync(SOURCE_DIR).filter(f => f.endsWith(".js")).sort();
for (const f of files) {
  const src = fs.readFileSync(path.join(SOURCE_DIR, f), "utf8");
  try {
    vm.runInContext(src, sandbox, { filename: f });
  } catch (e) {
    console.error(`Failed parsing ${f}:`, e.message);
    process.exit(1);
  }
}

const subjects = sandbox.window.SUBJECTS || [];

let totalQ = 0;
let totalWarnings = 0;
subjects.forEach(s => s.chapters.forEach(c => {
  totalQ += c.questions.length;
  totalWarnings += (c.parseWarnings || []).length;
  (c.parseWarnings || []).forEach(w => console.warn(`[${s.id}/${c.id}] ${w}`));
}));

fs.mkdirSync(SERVER_DATA_DIR, { recursive: true });
fs.writeFileSync(
  path.join(SERVER_DATA_DIR, "questions-full.json"),
  JSON.stringify(subjects)
);

const meta = subjects.map(s => ({
  id: s.id,
  name: s.name,
  chapters: s.chapters.map(c => ({
    id: c.id,
    name: c.name,
    total: c.questions.length,
    free: Math.min(FREE_PER_CHAPTER, c.questions.length)
  }))
}));
fs.writeFileSync(path.join(SERVER_DATA_DIR, "meta.json"), JSON.stringify(meta));

const freeSubjects = subjects.map(s => ({
  id: s.id,
  name: s.name,
  chapters: s.chapters.map(c => ({
    id: c.id,
    name: c.name,
    questions: c.questions.slice(0, FREE_PER_CHAPTER)
  }))
}));

const freeFileLines = [
  "/* AUTO-GENERATED by build-questions.js — do not hand-edit.",
  "   This file is public (loaded via <script> in index.html) and",
  "   contains ONLY the free sample questions. The full bank is",
  "   served from /api/questions.js to logged-in, paid users only. */",
  ""
];
freeSubjects.forEach(s => {
  freeFileLines.push(`registerSubject(${JSON.stringify(s.id)}, ${JSON.stringify(s.name)});`);
  s.chapters.forEach(c => {
    freeFileLines.push(
      `registerChapterObjects(${JSON.stringify(s.id)}, ${JSON.stringify(c.id)}, ${JSON.stringify(c.name)}, ${JSON.stringify(c.questions)});`
    );
  });
  freeFileLines.push("");
});
fs.mkdirSync(DATA_DIR, { recursive: true });
fs.writeFileSync(path.join(DATA_DIR, "free-questions.js"), freeFileLines.join("\n"));

// Clean out old per-subject public data files so nothing leaks the full bank
fs.readdirSync(DATA_DIR).forEach(f => {
  if (f !== "free-questions.js") fs.unlinkSync(path.join(DATA_DIR, f));
});

console.log(`Built ${subjects.length} subjects, ${totalQ} questions total (${totalWarnings} parse warnings).`);
console.log("Wrote server-data/questions-full.json (private), server-data/meta.json, data/free-questions.js (public).");
